@pytest.mark.django_db(transaction=True)
class TestFactClearConcurrency:
    """A clear must not wipe facts that a concurrent job saves while this job finishes."""

    def test_clear_waits_for_a_concurrent_fact_save(self, organization, artifacts_dir):
        inv = Inventory.objects.create(organization=organization, name='race-inv')
        host = inv.hosts.create(name='target', ansible_facts={'stale': True}, ansible_facts_modified=now() - timedelta(hours=1))
        job_created = now() - timedelta(minutes=5)
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)
        os.remove(os.path.join(artifacts_dir, 'fact_cache', 'target'))  # this job cleared the facts

        saving, release = threading.Event(), threading.Event()
        errors = []

        def concurrent_job_saves_facts():
            try:
                with transaction.atomic():
                    Host.objects.filter(pk=host.pk).update(ansible_facts={'from_concurrent_job': True}, ansible_facts_modified=now())
                    saving.set()
                    assert release.wait(10)
            except Exception as e:  # surfaced by the test after join
                errors.append(e)
            finally:
                connection.close()

        def finish():
            try:
                assert saving.wait(10)
                finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id, job_created=job_created)
            except Exception as e:  # surfaced by the test after join
                errors.append(e)
            finally:
                connection.close()

        threads = [threading.Thread(target=concurrent_job_saves_facts), threading.Thread(target=finish)]
        for thread in threads:
            thread.start()
        # Commit the concurrent save only once finish_fact_cache is waiting on the host's row lock
        with connection.cursor() as cursor:
            for _ in range(100):
                cursor.execute("SELECT count(*) FROM pg_stat_activity WHERE datname = current_database() AND wait_event_type = 'Lock'")
                if cursor.fetchone()[0]:
                    break
                time.sleep(0.1)
            else:
                release.set()
                pytest.fail('finish_fact_cache never waited for the concurrent fact save')
        release.set()
        for thread in threads:
            thread.join(30)
        assert not errors

        host.refresh_from_db()
        assert host.ansible_facts == {'from_concurrent_job': True}


