@pytest.mark.django_db
class TestSchemaQualifiedFactCache:
    """ansible-core 2.19+ keeps facts in s1_<host> files wrapped as {"__payload__": "<json>"}."""

    @pytest.fixture
    def inv(self, organization):
        return Inventory.objects.create(organization=organization, name='schema-inv')

    def _host(self, inv, name, facts):
        return inv.hosts.create(name=name, ansible_facts=facts, ansible_facts_modified=now() - timedelta(hours=1))

    def test_start_writes_both_formats(self, inv, artifacts_dir):
        facts = {'a': 1, 'secret': {'__ansible_vault': 'CIPHER'}}
        self._host(inv, 'web1', facts)
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        fact_cache_dir = os.path.join(artifacts_dir, 'fact_cache')
        with open(os.path.join(fact_cache_dir, 'web1')) as f:
            assert json.load(f) == facts
        with open(os.path.join(fact_cache_dir, 's1_web1')) as f:
            wrapped = json.load(f)
        assert list(wrapped) == ['__payload__']
        assert json.loads(wrapped['__payload__']) == {'a': 1, 'secret': {'value': 'CIPHER', 'tags': [], '__ansible_type': 'EncryptedString'}}

    def test_finish_reads_schema_file_and_strips_tags(self, inv, artifacts_dir):
        host = self._host(inv, 'web1', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'), _schema_payload(TAGGED_PAYLOAD_FACTS))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == TAGGED_PAYLOAD_PLAIN

    def test_finish_reads_schema_file_for_host_without_prior_facts(self, inv, artifacts_dir):
        host = inv.hosts.create(name='fresh')
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)
        assert os.listdir(os.path.join(artifacts_dir, 'fact_cache')) == []

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 's1_fresh'), _schema_payload({'gathered': True}))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'gathered': True}

    def test_schema_file_removed_clears_facts(self, inv, artifacts_dir):
        """meta: clear_facts under ansible-core 2.19+ deletes s1_<host> and leaves our plain file alone."""
        host = self._host(inv, 'web1', {'stale': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        os.remove(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {}

    def test_untouched_files_leave_facts_alone(self, inv, artifacts_dir):
        host = self._host(inv, 'web1', {'keep': True})
        modified = host.ansible_facts_modified
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'keep': True}
        assert host.ansible_facts_modified == modified

    def test_plain_file_still_works(self, inv, artifacts_dir):
        """Older ansible-core updates the plain file and never touches s1_<host>."""
        host = self._host(inv, 'web1', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 'web1'), {'new': True})
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'new': True}

    def test_host_named_like_schema_file(self, inv, artifacts_dir):
        """A host literally named s1_<other> keeps its plain file; <other> gets no schema copy."""
        web = self._host(inv, 'web1', {'web': True})
        prefixed = self._host(inv, 's1_web1', {'prefixed': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        with open(os.path.join(artifacts_dir, 'fact_cache', 's1_web1')) as f:
            assert json.load(f) == {'prefixed': True}

        # older ansible-core gathers facts for the s1_web1 host
        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'), {'prefixed': 'new'})
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        web.refresh_from_db()
        prefixed.refresh_from_db()
        assert web.ansible_facts == {'web': True}
        assert prefixed.ansible_facts == {'prefixed': 'new'}

    def test_corrupt_schema_file_falls_back_to_plain(self, inv, artifacts_dir):
        host = self._host(inv, 'web1', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'), {'__payload__': 'not json'})
        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 'web1'), {'new': True})
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'new': True}
