@pytest.mark.django_db
class TestSchemaQualifiedFactCache:
    """ansible-core 2.19+ keeps facts in s1_<host> files wrapped as {"__payload__": "<json>"}."""

    @pytest.fixture
    def inv(self, organization):
        return Inventory.objects.create(organization=organization, name='schema-inv')

    def _host(self, inv, name, facts):
        return inv.hosts.create(name=name, ansible_facts=facts, ansible_facts_modified=now() - timedelta(hours=1))

    def test_start_writes_both_formats(self, inv, artifacts_dir):
        facts = {'a': 1, 'secret': {'__ansible_vault': 'CIPHER'}}
        self._host(inv, 'web1', facts)
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        fact_cache_dir = os.path.join(artifacts_dir, 'fact_cache')
        with open(os.path.join(fact_cache_dir, 'web1')) as f:
            assert json.load(f) == facts
        with open(os.path.join(fact_cache_dir, 's1_web1')) as f:
            wrapped = json.load(f)
        assert list(wrapped) == ['__payload__']
        # ansible-core 2.19+ can't cache a value it hasn't decrypted (EncryptedString decodes
        # to its ciphertext as a plain string), so the vault marker is passed through as a dict
        assert json.loads(wrapped['__payload__']) == facts

    def test_finish_reads_schema_file_and_strips_tags(self, inv, artifacts_dir):
        host = self._host(inv, 'web1', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'), _schema_payload(TAGGED_PAYLOAD_FACTS))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == TAGGED_PAYLOAD_PLAIN

    def test_decrypted_vault_values_are_stored_encrypted(self, inv, artifacts_dir):
        """ansible-core 2.19+ caches a decrypted vaulted value as plaintext tagged with its ciphertext."""
        host = self._host(inv, 'web1', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        # captured from ansible-core 2.21: set_fact from a vaulted var and from an inline !vault
        vaulted = {
            'value': 's3cret',
            'tags': [
                {'ciphertext': '$ANSIBLE_VAULT;1.1;AES256\nabc', '__ansible_type': 'VaultedValue'},
                {'path': '/v/vars.yml', 'line_num': 1, 'col_num': 10, '__ansible_type': 'Origin'},
            ],
            '__ansible_type': '_AnsibleTaggedStr',
        }
        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'), _schema_payload({'templated': vaulted, 'nested': [{'secret': vaulted}]}))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        marker = {'__ansible_vault': '$ANSIBLE_VAULT;1.1;AES256\nabc'}
        assert host.ansible_facts == {'templated': marker, 'nested': [{'secret': marker}]}
        assert 's3cret' not in json.dumps(host.ansible_facts)

    def test_finish_reads_schema_file_for_host_without_prior_facts(self, inv, artifacts_dir):
        host = inv.hosts.create(name='fresh')
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)
        assert os.listdir(os.path.join(artifacts_dir, 'fact_cache')) == []

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 's1_fresh'), _schema_payload({'gathered': True}))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'gathered': True}

    def test_schema_file_removed_clears_facts(self, inv, artifacts_dir):
        """meta: clear_facts under ansible-core 2.19+ deletes s1_<host> and leaves our plain file alone."""
        host = self._host(inv, 'web1', {'stale': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        os.remove(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {}

    def test_untouched_files_leave_facts_alone(self, inv, artifacts_dir):
        host = self._host(inv, 'web1', {'keep': True})
        modified = host.ansible_facts_modified
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'keep': True}
        assert host.ansible_facts_modified == modified

    def test_plain_file_still_works(self, inv, artifacts_dir):
        """Older ansible-core updates the plain file and never touches s1_<host>."""
        host = self._host(inv, 'web1', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 'web1'), {'new': True})
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'new': True}

    def test_schema_write_failure_does_not_clear_facts(self, inv, artifacts_dir):
        """A name that only fits the filesystem without the s1_ prefix still works on older ansible-core."""
        name = 'h' * 253  # "s1_" + name exceeds the 255-byte filename limit
        host = self._host(inv, name, {'keep': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)
        assert os.listdir(os.path.join(artifacts_dir, 'fact_cache')) == [name]

        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'keep': True}

    def test_reserved_key_facts_are_not_put_in_the_schema_payload(self, inv, artifacts_dir):
        """ansible-core 2.19+ would read the dict as type metadata (or abort on an unknown type)."""
        facts = {'x': {'__ansible_type': '_AnsibleTaggedStr', 'value': 'original', 'tags': []}, 'y': [{'__ansible_type': 'bogus'}]}
        host = self._host(inv, 'web1', facts)
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)
        assert os.listdir(os.path.join(artifacts_dir, 'fact_cache')) == ['web1']

        # older ansible-core still round-trips the dict untouched
        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 'web1'), dict(facts, z=1))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == dict(facts, z=1)

    def test_plain_file_with_a_payload_fact(self, inv, artifacts_dir):
        """Older ansible-core caches a lone cacheable fact named __payload__ exactly like a wrapper."""
        host = self._host(inv, 'web1', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 'web1'), {'__payload__': 'run-7'})
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'__payload__': 'run-7'}

    def test_malformed_type_metadata_falls_back_to_plain(self, inv, artifacts_dir):
        """A payload ansible would never write must not stop the other hosts' facts being saved."""
        web = self._host(inv, 'web1', {'old': True})
        other = self._host(inv, 'web2', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        fact_cache_dir = os.path.join(artifacts_dir, 'fact_cache')
        malformed = {'x': {'value': 'v', 'tags': 1, '__ansible_type': '_AnsibleTaggedStr'}}
        _write_as_ansible(os.path.join(fact_cache_dir, 's1_web1'), _schema_payload(malformed))
        _write_as_ansible(os.path.join(fact_cache_dir, 'web1'), {'new': True})
        _write_as_ansible(os.path.join(fact_cache_dir, 's1_web2'), _schema_payload({'new': 2}))
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        web.refresh_from_db()
        other.refresh_from_db()
        assert web.ansible_facts == {'new': True}
        assert other.ansible_facts == {'new': 2}

    def test_start_streams_hosts_given_their_names(self, inv, artifacts_dir):
        """With host_names, hosts are read once, so a generator over several inventories works."""
        old = now() - timedelta(minutes=1)
        hosts = [
            Host(name='web1', ansible_facts={'web': True}, ansible_facts_modified=old),
            Host(name='s1_web1', ansible_facts={'p': True}, ansible_facts_modified=old),
        ]
        start_fact_cache((h for h in hosts), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id, host_names={'web1', 's1_web1'})

        fact_cache_dir = os.path.join(artifacts_dir, 'fact_cache')
        assert sorted(os.listdir(fact_cache_dir)) == ['s1_s1_web1', 's1_web1', 'web1']
        with open(os.path.join(fact_cache_dir, 's1_web1')) as f:
            assert json.load(f) == {'p': True}

    def test_corrupt_schema_file_falls_back_to_plain(self, inv, artifacts_dir):
        host = self._host(inv, 'web1', {'old': True})
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)

        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'), {'__payload__': 'not json'})
        _write_as_ansible(os.path.join(artifacts_dir, 'fact_cache', 'web1'), {'new': True})
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)

        host.refresh_from_db()
        assert host.ansible_facts == {'new': True}


@pytest.mark.django_db
class TestSchemaFileNameCollision:
    """Hosts web1 and s1_web1 both claim the file s1_web1: it is the older ansible-core
    file of s1_web1 and the newer ansible-core file of web1. Older ansible-core gets it."""

    @pytest.fixture
    def hosts(self, organization, artifacts_dir):
        inv = Inventory.objects.create(organization=organization, name='collision-inv')
        old = now() - timedelta(hours=1)
        web = inv.hosts.create(name='web1', ansible_facts={'web': True}, ansible_facts_modified=old)
        prefixed = inv.hosts.create(name='s1_web1', ansible_facts={'prefixed': True}, ansible_facts_modified=old)
        start_fact_cache(inv.hosts.all(), artifacts_dir=artifacts_dir, timeout=0, inventory_id=inv.id)
        return inv, web, prefixed

    def _finish(self, inv, artifacts_dir, web, prefixed):
        finish_fact_cache(inv.hosts, artifacts_dir=artifacts_dir, inventory_id=inv.id)
        web.refresh_from_db()
        prefixed.refresh_from_db()

    def test_shared_file_belongs_to_older_format(self, hosts, artifacts_dir):
        """Older ansible-core (the stock EE) keeps reading s1_web1's facts as it always has;
        web1 gets no schema copy, so newer ansible-core sees no cached facts for it."""
        fact_cache_dir = os.path.join(artifacts_dir, 'fact_cache')
        assert sorted(os.listdir(fact_cache_dir)) == ['s1_s1_web1', 's1_web1', 'web1']
        with open(os.path.join(fact_cache_dir, 's1_web1')) as f:
            assert json.load(f) == {'prefixed': True}

    # The shared file s1_web1 is settled by the files only one ansible-core touches:
    # older ansible-core writes/removes web1, newer writes/removes s1_s1_web1.

    def test_shared_file_removed_without_evidence_keeps_both_hosts_facts(self, hosts, artifacts_dir):
        """Older ansible-core clearing s1_web1 and newer ansible-core clearing web1 look the same."""
        inv, web, prefixed = hosts
        os.remove(os.path.join(artifacts_dir, 'fact_cache', 's1_web1'))

        self._finish(inv, artifacts_dir, web, prefixed)

        assert web.ansible_facts == {'web': True}
        assert prefixed.ansible_facts == {'prefixed': True}

    def test_old_ansible_clears_both_hosts(self, hosts, artifacts_dir):
        inv, web, prefixed = hosts
        fact_cache_dir = os.path.join(artifacts_dir, 'fact_cache')
        os.remove(os.path.join(fact_cache_dir, 'web1'))
        os.remove(os.path.join(fact_cache_dir, 's1_web1'))

        self._finish(inv, artifacts_dir, web, prefixed)

        assert web.ansible_facts == {}
        assert prefixed.ansible_facts == {}

    def test_new_ansible_clears_both_hosts(self, hosts, artifacts_dir):
        inv, web, prefixed = hosts
        fact_cache_dir = os.path.join(artifacts_dir, 'fact_cache')
        os.remove(os.path.join(fact_cache_dir, 's1_web1'))
        os.remove(os.path.join(fact_cache_dir, 's1_s1_web1'))

        self._finish(inv, artifacts_dir, web, prefixed)

        assert web.ansible_facts == {}
        assert prefixed.ansible_facts == {}

