#!/usr/bin/env bash
# Regenerates baseline.sql and level.json: the schema of a database the
# Django application migrated from nothing, the rows its migrations wrote,
# and the last migration of each of its apps.
#
# It is run once per level, by hand, with the old application at hand: a
# throwaway PostgreSQL is migrated by the old image from the old source
# tree, and dumped. Nothing here touches a database that is in use.
#
#   OLD_SOURCE   the old application's source tree (a checkout of
#                github.com/ctrliq/ascender; required)
#   OLD_IMAGE    an image that can run its ascender-manage
#   PG_IMAGE     the PostgreSQL the dump is made with. The oldest version
#                the application is run against, since a dump loads into
#                newer servers and not always into older ones.
#   BASELINE_PG  a container holding a database already migrated this way
#                (named "ascender"); skips the migration, which takes minutes
#
# The dump leaves out what belongs to one installation (its INSTALL_UUID,
# its resource registry service id): first_run.sql, which is written by
# hand, gives each new database its own.
set -euo pipefail

OLD_SOURCE=${OLD_SOURCE:?set OLD_SOURCE to a checkout of github.com/ctrliq/ascender}
OLD_IMAGE=${OLD_IMAGE:-ghcr.io/ctrliq/ascender_devel:main}
PG_IMAGE=${PG_IMAGE:-quay.io/sclorg/postgresql-15-c9s:latest}
here=$(cd "$(dirname "$0")" && pwd)
pg=${BASELINE_PG:-}

if [ -z "$pg" ]; then
    pg=zz-baseline-pg
    net=zz-baseline-net
    work=$(mktemp -d)
    cleanup() {
        docker rm -f "$pg" >/dev/null 2>&1 || true
        docker network rm "$net" >/dev/null 2>&1 || true
        rm -rf "$work"
    }
    trap cleanup EXIT
    docker network create "$net" >/dev/null
    docker run -d --name "$pg" --network "$net" -e POSTGRESQL_USER=ascender -e POSTGRESQL_PASSWORD=baseline \
        -e POSTGRESQL_DATABASE=ascender "$PG_IMAGE" >/dev/null
    until docker exec "$pg" pg_isready -q; do sleep 1; done

    # The settings a production install had, less everything that is one
    # deployment's: no cluster, no Kubernetes, a key that is thrown away.
    cat > "$work/settings.py" <<'PY'
def get_secret():
    return open('/etc/tower/SECRET_KEY', 'rb').read().strip()

ADMINS = ()
SECRET_KEY = get_secret()
ALLOWED_HOSTS = ['*']
CLUSTER_HOST_ID = 'baseline'
PY
    cat > "$work/credentials.py" <<PY
DATABASES = {
    'default': {
        'ATOMIC_REQUESTS': True,
        'ENGINE': 'awx.main.db.profiled_pg',
        'NAME': "ascender",
        'USER': "ascender",
        'PASSWORD': "baseline",
        'HOST': '$pg',
        'PORT': "5432",
    }
}
PY
    head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n' > "$work/SECRET_KEY"
    chmod 644 "$work"/*
    docker run --rm --network "$net" -w /ascender_devel -v "$OLD_SOURCE":/ascender_devel:ro \
        -v "$work/settings.py":/etc/tower/settings.py:ro -v "$work/credentials.py":/etc/tower/conf.d/credentials.py:ro \
        -v "$work/SECRET_KEY":/etc/tower/SECRET_KEY:ro -e DJANGO_SETTINGS_MODULE=ascender.settings.production \
        --entrypoint /usr/local/bin/ascender-manage "$OLD_IMAGE" migrate --noinput
fi

dump() { docker exec "$pg" pg_dump -d ascender --no-owner --no-privileges "$@"; }

{
    echo "-- Generated by generate.sh; do not edit. See ../baseline.go."
    echo "-- Level: $(docker exec "$pg" psql -d ascender -Atc "SELECT app || '.' || name FROM django_migrations WHERE app = 'main' ORDER BY id DESC LIMIT 1")"
    echo
    dump --schema-only
    # The rows the migrations wrote: content types, permissions, the managed
    # credential types, the system job templates and their schedules, and
    # django_migrations itself, which is how a database says what level it is at.
    dump --data-only --column-inserts --exclude-table-data=conf_setting --exclude-table-data=dab_resource_registry_serviceid
} |
    # psql's own commands (newer pg_dump writes \restrict) are not SQL, and
    # the file is sent to the server as it is.
    grep -v '^\\' > "$here/baseline.sql"

docker exec "$pg" psql -d ascender -Atc "SELECT json_agg(json_build_object('app', app, 'name', name) ORDER BY app)
    FROM (SELECT DISTINCT ON (app) app, name FROM django_migrations ORDER BY app, id DESC) m" |
    python3 -c 'import json, sys; json.dump(json.load(sys.stdin), sys.stdout, indent=1); print()' > "$here/level.json"

echo "baseline.sql: $(wc -c < "$here/baseline.sql") bytes; level:"
cat "$here/level.json"
